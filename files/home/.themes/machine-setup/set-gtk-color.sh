#!/bin/bash
# set-gtk-color.sh <role> <hex|--get> - GTK app text colour and selection highlight, as marked blocks appended to the user GTK css files.
#   role text      : (1) every `color: #dedee2;` / `color: #dadade;` declaration of gtk-4.0/gtk.css (the cooked base text colours: .background, entries, ...), tagged
#                    `/*gt*/` after the first change so later changes find exactly those lines (never a colour-value replace; backgrounds untouched; lines inside
#                    KNOMADIC blocks skipped); (2) the foreground tokens window/view/sidebar/secondary_sidebar/card/dialog/popover/theme _fg_color (every libadwaita/GTK4 app, and
#                    adw-gtk3 GTK3 apps through ~/.config/gtk-3.0/gtk.css). NOT the headerbar text (headerbar_fg_color), NOT Thunar/Qt apps (own swatches).
#   role selection : the fill of selected text and selected rows that gtk-4.0/gtk.css hard-codes as accent literals (entries, text views, tree/column/grid
#                    views, flowbox, calendar days, labels) + theme_selected_bg_color/selected_bg_color for GTK3. Selected-row washes libadwaita compiles in
#                    itself (list rows, sidebars) still follow the accent.
# Blocks sit at the END of the file (later wins) and are skipped by the accent/background scripts (they skip KNOMADIC blocks). Delete a block
# (BEGIN..END) to go back to the stock/accent colours. No backups are written. Restart the apps to see a change.
#   role dark      : the GTK "dark application background" (view/card/dialog tokens: gtk-4.0 literals of that value; GTK3: view_bg_color block). Default #18181c.
#   role light     : the GTK "lighter application background" (window/sidebar/popover: Settings and every general GTK app). Default #2a2a33.
#                    dark/light replace ONLY the current value of their own role (read from the real token), never inside KNOMADIC blocks (per-app swatches),
#                    never on text/foreground lines, and dark also leaves every `headerbar` rule alone (the Titlebar swatch owns those). `default` restores
#                    the built-in value (what every GTK app without its own swatch gets); `--dry <hex>` reports what would change without writing.
# Usage: set-gtk-color.sh text|selection <hex>   |   set-gtk-color.sh text|selection --get
#        set-gtk-color.sh scrollbar|inactive on|off|--get   (scrollbar: GTK scrollbars follow the accent; inactive: no colour change when a window is inactive, generated from the sheet / stock adw-gtk3)
#        set-gtk-color.sh dark|light <hex|default|--get>   |   set-gtk-color.sh dark|light --dry <hex>
set -euo pipefail
ROLE="${1:-}"; ARG="${2:-}"
GTK4="${GTK4_CSS:-$HOME/.config/gtk-4.0/gtk.css}"; GTK3="${GTK3_CSS:-$HOME/.config/gtk-3.0/gtk.css}"
case "$ROLE" in text|selection|dark|light|scrollbar|inactive|brave) ;; *) echo "Usage: $0 text|selection|dark|light <hex|--get>   |   $0 scrollbar|inactive on|off|--get"; exit 1 ;; esac
# Brave theme extension (~/.themes/brave-theme/manifest.json, loaded once in brave://extensions): frame/titlebar = the DARK role, toolbar/tabs/new tab page = the LIGHT role, text = the GTK text colour.
# Regenerated here (`set-gtk-color.sh brave`) and automatically after every dark/light change; Brave needs the extension card's reload button (or a restart) to pick it up.
brave_theme() {
    local d="$HOME/.themes/brave-theme"; [ -d "$d" ] || return 0
    python3 -I - "$GTK4" "$d/manifest.json" "$("$0" text --get 2>/dev/null)" <<'PYB'
import re, sys, json
t = open(sys.argv[1]).read()
def tok(n, dflt):
    m = re.findall(r'@define-color %s #([0-9a-fA-F]{6})' % n, t); return m[-1] if m else dflt   # last one wins (the gtk-text block sits at the end)
rgb = lambda h: [int(h[i:i + 2], 16) for i in (0, 2, 4)]
dark, light = tok('view_bg_color', '18181c'), tok('window_bg_color', '2a2a33')
text = sys.argv[3] if re.fullmatch(r'[0-9a-fA-F]{6}', sys.argv[3] if len(sys.argv) > 3 else '') else tok('window_fg_color', 'dedee2')   # the Text (GTK apps) swatch value
c = {'frame': dark, 'frame_inactive': dark, 'frame_incognito': dark, 'frame_incognito_inactive': dark, 'toolbar': light, 'ntp_background': light, 'omnibox_background': dark,
     'tab_text': text, 'tab_background_text': text, 'bookmark_text': text, 'ntp_text': text, 'omnibox_text': text}
m = {'manifest_version': 3, 'version': '1.0', 'name': 'Asahi GTK colours',
     'description': 'generated by set-gtk-color.sh brave: frame #%s (dark role), toolbar/tabs/new tab #%s (light role), text #%s' % (dark, light, text),
     'theme': {'colors': dict((k, rgb(v)) for k, v in c.items())}}
m['theme']['colors']['button_background'] = [0, 0, 0, 0]
open(sys.argv[2], 'w').write(json.dumps(m, indent=2) + '\n')
print('  brave theme: frame #%s toolbar #%s text #%s (reload the extension in brave://extensions)' % (dark, light, text))
PYB
}
if [ "$ROLE" == "brave" ]; then brave_theme; exit 0; fi
case "$ROLE" in dark|light)
python3 - "$ROLE" "$ARG" "${3:-}" "$GTK4" "$GTK3" <<'PYEOF'
import re, sys
role, arg, arg2, g4, g3 = sys.argv[1:6]
DEFAULT = {'dark': '18181c', 'light': '2a2a33'}[role]
TOK = {'dark': 'view_bg_color', 'light': 'window_bg_color'}[role]       # the gtk-4.0 token that carries the role's current value
T3 = {'dark': ['view_bg_color'], 'light': ['window_bg_color', 'sidebar_bg_color']}[role]
B = '/* KNOMADIC: gtk-%s BEGIN - do not edit by hand, see set-gtk-color.sh */' % role
E = '/* KNOMADIC: gtk-%s END */' % role
blk_re = re.compile(r'\n*' + re.escape(B) + r'.*?' + re.escape(E) + r'\n?', re.S)
FG = re.compile(r'fg[_-]?color|foreground|text[_-]?color|\btext\b|^\s*color\s*:', re.I)
t4 = open(g4).read()
m = re.search(r'@define-color %s #([0-9a-fA-F]{6})' % TOK, t4)
cur = m.group(1).lower() if m else ''
if arg == '--get':
    print(cur); sys.exit(0)
dry = arg == '--dry'
new = DEFAULT if arg == 'default' else (arg2 if dry else arg).lstrip('#').lower()
if not re.fullmatch(r'[0-9a-f]{6}', new):
    sys.exit("Error: '%s' doesn't look like a valid 6-digit hex color." % arg)
if not cur:
    sys.exit('Error: no current %s found in %s' % (TOK, g4))
out, inblk, sel, changed, skipped = [], False, '', 0, 0
for ln in t4.split('\n'):
    if ln.startswith('/* KNOMADIC:') and ' BEGIN' in ln: inblk = True
    if not inblk and ln and not ln[0] in ' \t@/}' and ln.rstrip().endswith('{'): sel = ln
    if not inblk and cur in ln.lower() and not FG.search(ln):
        if role == 'dark' and ('headerbar' in sel or 'headerbar_' in ln):
            skipped += 1
        else:
            changed += len(re.findall(cur, ln, re.I))
            ln = re.sub(cur, new, ln, flags=re.I)
    if ln.startswith('/* KNOMADIC:') and ' END' in ln: inblk = False
    out.append(ln)
print('%s: #%s -> #%s: %d gtk-4.0 values changed%s' % (role, cur, new, changed, (', %d headerbar values left to the Titlebar swatch' % skipped) if skipped else ''))
if dry:
    print('(dry run, nothing written)'); sys.exit(0)
open(g4, 'w').write('\n'.join(out))
try: t3 = open(g3).read()
except OSError: t3 = None
if t3 is not None:
    t3 = blk_re.sub('', t3).rstrip('\n') + '\n'
    if new != DEFAULT:
        t3 = t3.rstrip('\n') + '\n\n' + B + '\n' + ''.join('@define-color %s #%s;\n' % (n, new) for n in T3) + E + '\n'
    open(g3, 'w').write(t3)
    print('  gtk-3.0: %s' % ('block removed (default)' if new == DEFAULT else ', '.join(T3) + ' -> #' + new))
PYEOF
# the generated "no colour change when inactive" block copies literal values of the sheet (these backgrounds included): regenerate it
if [ "$ARG" != "--get" ] && [ "$ARG" != "--dry" ] && [ "$("$0" inactive --get 2>/dev/null)" == "on" ]; then
    "$0" inactive on | sed 's/^/  /'
    grep -q 'KNOMADIC: flat-surfaces BEGIN' "$GTK4" 2>/dev/null && [ -z "${GTK4_CSS:-}" ] && "$(dirname "$0")/set-flat-surfaces.sh" | sed 's/^/  /'   # flat surfaces stay the LAST block
fi
[ "$ARG" == "--get" ] || [ "$ARG" == "--dry" ] || { [ -z "${GTK4_CSS:-}" ] && brave_theme; echo; echo "Done. Restart the GTK apps to see the change."; }
exit 0 ;; esac
python3 - "$ROLE" "$ARG" "$GTK4" "$GTK3" <<'PYEOF'
import re, sys
role, arg, g4, g3 = sys.argv[1:5]
NAME = 'gtk-' + role
B = '/* KNOMADIC: %s BEGIN - do not edit by hand, see set-gtk-color.sh */' % NAME
E = '/* KNOMADIC: %s END */' % NAME
blk_re = re.compile(re.escape(B) + r'.*?' + re.escape(E), re.S)
TEXT = ['window_fg_color', 'view_fg_color', 'sidebar_fg_color', 'secondary_sidebar_fg_color', 'card_fg_color', 'dialog_fg_color', 'popover_fg_color', 'theme_fg_color', 'fg_color', 'theme_unfocused_fg_color']
SEL = ['treeview.view:selected', 'treeview.view:selected:focus', 'columnview.view:selected', 'columnview.view:selected:focus', 'calendar > grid > label.day-number:selected',
       'entry > text > selection', 'gridview > child:selected', 'flowbox > flowboxchild:selected', 'textview > text selection:focus', 'textview > text selection',
       'iconview:selected:focus', '.view:selected:focus', 'label > selection',
       'listview > row:selected', 'listview > row:selected:focus', 'listview > row:selected:backdrop', 'list.view > row:selected', 'columnview > listview > row:selected']
SEL3 = ['entry selection', 'entry selection:focus', 'spinbutton:not(.vertical) selection', 'textview text selection', 'textview text selection:focus', '.view text selection', '.view text selection:focus',
        'iconview text selection', 'iconview text selection:focus', 'label selection', '.view text:selected', 'textview text:selected', 'iconview text:selected', 'flowbox flowboxchild:selected']
def body4(h):
    if role == 'text':
        return ''.join('@define-color %s #%s;\n' % (n, h) for n in TEXT)
    return ',\n'.join(SEL) + ' {\n  background-color: #%s;\n}\n' % h
def body3(h):
    if role == 'text':
        return ''.join('@define-color %s #%s;\n' % (n, h) for n in TEXT)
    # adw-gtk3 paints text selection as alpha(@accent_bg_color, 0.25) in its own rules (the two colours below are not used for it): set the fill directly
    return ('@define-color theme_selected_bg_color #%s;\n@define-color selected_bg_color #%s;\n' % (h, h)) + ',\n'.join(SEL3) + ' {\n  background-color: #%s;\n}\n' % h
def literals(text, new):
    out, inblk = [], False
    for ln in text.split('\n'):
        if ln.startswith('/* KNOMADIC:') and ' BEGIN' in ln: inblk = True
        m = None if inblk else re.match(r'^(\s*)color: #([0-9a-fA-F]{6});( /\*gt\*/)?$', ln)
        if m and (m.group(3) or m.group(2).lower() in ('dedee2', 'dadade', 'dedede', 'dadada')):
            ln = '%scolor: #%s; /*gt*/' % (m.group(1), new)
        if ln.startswith('/* KNOMADIC:') and ' END' in ln: inblk = False
        out.append(ln)
    return '\n'.join(out)
def read(p):
    try: return open(p).read()
    except OSError: return None
SB4 = """scrollbar > range > trough > slider,
scrollbar.overlay-indicator:not(.dragging):not(.hovering) > range > trough > slider {
  background-color: @accent_bg_color;
}
scrollbar > range > trough > slider:hover {
  background-color: @accent_bg_color;
}
scrollbar > range > trough > slider:hover:active {
  background-color: mix(@accent_bg_color, #000000, 0.15);
}
scrollbar > range > trough > slider:disabled {
  background-color: transparent;
}
scrollbar.overlay-indicator:not(.dragging):not(.hovering) {
  opacity: 0.7;
}
scrollbar.overlay-indicator.dragging,
scrollbar.overlay-indicator.hovering {
  opacity: 1;
}
scrollbar.overlay-indicator {
  transition: opacity 250ms ease-in-out;
}
"""
SB3 = """scrollbar slider,
scrollbar.overlay-indicator:not(.dragging):not(.hovering) slider {
  background-color: @accent_bg_color;
}
scrollbar slider:hover {
  background-color: @accent_bg_color;
}
scrollbar slider:hover:active {
  background-color: mix(@accent_bg_color, #000000, 0.15);
}
scrollbar slider:disabled {
  background-color: transparent;
}
scrollbar.fine-tune slider, scrollbar.fine-tune slider:hover, scrollbar.fine-tune slider:active {
  background-color: @accent_bg_color;
}
scrollbar.overlay-indicator:not(.dragging):not(.hovering) {
  opacity: 0.7;
}
scrollbar.overlay-indicator.dragging,
scrollbar.overlay-indicator.hovering {
  opacity: 1;
}
scrollbar.overlay-indicator {
  transition: opacity 250ms ease-in-out;
}
"""
if role == 'inactive':
    # user rule: no colour may change with window activity. For every `S:backdrop` rule of the sheet that sets a colour differently from the active rule `S`, write
    # `S:backdrop { prop: <value of S> }` into one marked block at the END of the file (GTK4: from the user sheet itself, our own KNOMADIC blocks excluded; GTK3: from the stock
    # adw-gtk3-dark theme the GTK3 apps use). :disabled / :insensitive rules are left alone (disabled controls keep their dimming). Re-run after the sheet changes.
    if arg == '--get':
        print('on' if blk_re.search(read(g4) or '') else 'off'); sys.exit(0)
    if arg not in ('on', 'off'):
        sys.exit('Usage: set-gtk-color.sh inactive on|off|--get')
    import os
    PROPS = ('color', 'background-color', 'background-image', 'border-color', 'border-top-color', 'border-bottom-color', 'border-left-color', 'border-right-color')
    SKIP = re.compile(r':disabled|:insensitive|:not\(:backdrop\)|windowcontrols|titlebutton|separator\.titlebutton|^headerbar (entry|button|switch|searchentry|\.linked)')
    def rules(txt):
        txt = re.sub(r'/\*.*?\*/', '', txt, flags=re.S)
        for m in re.finditer(r'([^{}@][^{}]*)\{([^{}]*)\}', txt):
            sels = [x.strip() for x in m.group(1).split(',') if x.strip()]
            props = {}
            for d in m.group(2).split(';'):
                if ':' in d:
                    k, v = d.split(':', 1); props[k.strip()] = v.strip()
            yield sels, props
    def block_for(txt):
        txt = re.sub(r'/\* KNOMADIC: [^*]* BEGIN.*?/\* KNOMADIC: [^*]* END \*/', '', txt, flags=re.S)
        base, back = {}, []
        for sels, props in rules(txt):
            for sel in sels:
                if ':backdrop' in sel: back.append((sel, props))
                else: base.setdefault(sel, {}).update(props)
        out, seen, skipped = [], set(), 0
        for sel, props in back:
            if SKIP.search(sel): continue
            b = sel.replace(':backdrop', '')
            want = {k: base[b][k] for k in PROPS if k in props and k in base.get(b, {}) and props[k] != base[b][k]}
            if len(want) < len([k for k in PROPS if k in props]) : skipped += 1
            if not want: continue
            key = (sel, tuple(sorted(want.items())))
            if key in seen: continue
            seen.add(key); out.append('%s {\n%s}\n' % (sel, ''.join('  %s: %s;\n' % kv for kv in want.items())))
        return ''.join(out), len(out), skipped
    g3theme = '/usr/share/themes/adw-gtk3-dark/gtk-3.0/gtk-dark.css'
    if not os.path.exists(g3theme): g3theme = os.path.expanduser('~/.themes/adw-gtk3-dark/gtk-3.0/gtk-dark.css')
    for path, srcfile in ((g4, None), (g3, g3theme)):
        t = read(path)
        if t is None:
            print('  skipped (missing): ' + path); continue
        m = blk_re.search(t)
        if m: t = t[:m.start()].rstrip('\n') + '\n' + t[m.end():].lstrip('\n')
        if arg == 'on':
            src = open(srcfile).read() if srcfile else t
            body, n, skipped = block_for(src)
            t = t.rstrip('\n') + '\n\n%s\n%s%s\n' % (B, body, E)
            print('  inactive on: %d override rules in %s (%d rules had a colour with no active value to copy)' % (n, path, skipped))
        else:
            print('  inactive off in ' + path)
        open(path, 'w').write(t)
    sys.exit(0)
if role == 'scrollbar':   # follows the accent colour through the named colour, so set-accent-color.sh needs no extra step
    if arg == '--get':
        print('on' if blk_re.search(read(g4) or '') else 'off'); sys.exit(0)
    if arg not in ('on', 'off'):
        sys.exit('Usage: set-gtk-color.sh scrollbar on|off|--get')
    for path, body in ((g4, SB4), (g3, SB3)):
        t = read(path)
        if t is None:
            print('  skipped (missing): ' + path); continue
        m = blk_re.search(t)
        if m: t = t[:m.start()].rstrip('\n') + '\n' + t[m.end():].lstrip('\n')
        if arg == 'on': t = t.rstrip('\n') + '\n\n%s\n%s%s\n' % (B, body, E)
        open(path, 'w').write(t)
        print('  scrollbar %s in %s' % (arg, path))
    sys.exit(0)
if arg == '--get':
    t = read(g4) or ''
    m = blk_re.search(t)
    h = None
    if role == 'text' and re.search(r'color: #([0-9a-fA-F]{6}); /\*gt\*/', t):
        h = re.search(r'color: #([0-9a-fA-F]{6}); /\*gt\*/', t)
    elif m:
        h = re.search(r'#([0-9a-fA-F]{6})', m.group(0))
    elif role == 'text':
        h = re.search(r'^\s*color: #(dedee2|dedede);', t, re.M) or re.search(r'@define-color window_fg_color #([0-9a-fA-F]{6})', t)
    else:
        h = re.search(r'@define-color accent_bg_color #([0-9a-fA-F]{6})', t)
    print(h.group(1).lower() if h else '')
    sys.exit(0)
new = arg.lstrip('#').lower()
if not re.fullmatch(r'[0-9a-f]{6}', new):
    sys.exit("Error: '%s' doesn't look like a valid 6-digit hex color." % arg)
for path, body in ((g4, body4), (g3, body3)):
    t = read(path)
    if t is None:
        print('  skipped (missing): ' + path); continue
    blk = '%s\n%s%s' % (B, body(new), E)
    m = blk_re.search(t)
    t = t[:m.start()] + blk + t[m.end():] if m else t.rstrip('\n') + '\n\n' + blk + '\n'
    if role == 'text' and path == g4:
        t = literals(t, new)
    open(path, 'w').write(t)
    print('  %s -> #%s in %s' % (role, new, path))
PYEOF
[ "$ARG" == "--get" ] || { echo; echo "Done. Restart the GTK apps to see the change."; }
