#!/bin/bash
# set-shell-accent-color.sh - GNOME Shell's own accent color (workspace-thumbnail
# selection, folder-popup focus, active Quick Settings toggles, calendar today
# circle, and - via gen-shell-accent-overrides.py - every other stock use of the
# system accent: sliders, switches, focus rings, ...). Independent of the
# GTK/Qt/KDE accent (set-accent-color.sh).
#
# SAFER than the old version (ported from the Debian setup, 2026-10-05): the old
# script did a blind file-wide `sed s/OLD/NEW/g`, which would also recolor any
# QS/Calendar role that happened to share the accent's hex. Now it edits only:
#   1. the 3 hand-written accent blocks (selection group, .quick-toggle:checked,
#      split-toggle arrow) - anchor-scoped, first hex after each anchor
#   2. the `.calendar-day.calendar-today` companion rule - anchor-scoped
#   3. the accent-unified-auto-generated block - regenerated by
#      gen-shell-accent-overrides.py (never sed)
#   4. the accent-mix fragments inside the qs-inactive-toggle block only
#
# ALSO sets the GDM login-screen accent (added 2026-10-06): rebuilds
# /usr/share/gnome-shell/gnome-shell-theme.gresource from the pristine
# gnome-shell-theme.gresource.orig with -st-accent-color replaced by the literal
# hex in the dark/light/high-contrast css and the pale focus rings made solid,
# then installs it via pkexec (graphical password prompt). A gnome-shell update
# overwrites the gresource: run `--gdm` to re-apply the current color (the script
# also re-applies automatically when invoked with the unchanged color and GDM is
# out of date). GDM_DRYRUN=1 builds only and prints the path. Needs glib2-devel.
#
# CURRENT_HEX is the known-current value, hardcoded and self-updating.
# SHELL_CSS=<path> env override lets you test on a scratch copy.
#
# Usage: ./set-shell-accent-color.sh <new-hex-color>
#        ./set-shell-accent-color.sh --get
#        ./set-shell-accent-color.sh --gdm        (re-apply current color to GDM only)

set -euo pipefail

CURRENT_HEX="5a3e8b"

GRES=/usr/share/gnome-shell/gnome-shell-theme.gresource

# Prints the accent hex baked into the installed GDM gresource, or "stock" if unpatched.
gdm_installed() {
    python3 - "$GRES" <<'PYEOF'
import re, sys
import gi
gi.require_version('Gio', '2.0')
from gi.repository import Gio
r = Gio.Resource.load(sys.argv[1]); r._register()
t = bytes(Gio.resources_lookup_data('/org/gnome/shell/theme/gnome-shell-dark.css', 0).get_data()).decode()
if '-st-accent-color' in t:
    print('stock')
else:
    m = re.search(r'inset 0 0 0 2px #([0-9a-f]{6}) !important', t)
    print(m.group(1) if m else 'unknown')
PYEOF
}

# Overview background from the user shell theme (`#overview { background-color: #xxxxxx }`);
# GDM's #lockDialogGroup is kept equal to it (set-shell-background-color.sh edits both).
overview_bg() {
    python3 - "${SHELL_CSS:-$HOME/.themes/Adwaita-custom/gnome-shell/gnome-shell.css}" <<'PYEOF'
import re, sys
m = re.search(r'^#overview\s*\{[^}]*?background-color:\s*#([0-9a-fA-F]{6})', open(sys.argv[1]).read(), re.M)
print(m.group(1).lower() if m else '')
PYEOF
}

gdm_apply() {
    local hex="$1" src="$GRES.orig" work bg
    bg="$(overview_bg)"
    if [ ! -f "$src" ]; then
        if [ "$(gdm_installed)" == "stock" ]; then src="$GRES"
        else echo "  GDM: no pristine $GRES.orig and installed file is patched - skipped." >&2; return 1; fi
    fi
    command -v glib-compile-resources >/dev/null || { echo "  GDM: glib-compile-resources missing (dnf install glib2-devel) - skipped." >&2; return 1; }
    work="$(mktemp -d)"
    ( cd "$work"
      gresource list "$src" > list.txt
      while read -r f; do mkdir -p ".$(dirname "$f")"; gresource extract "$src" "$f" > ".$f"; done < list.txt
      for v in dark light high-contrast; do
          css="org/gnome/shell/theme/gnome-shell-$v.css"
          sed -i "s/inset 0 0 0 2px st-transparentize(st-mix(-st-accent-color, #ffffff, 60%), 0\.2)/inset 0 0 0 2px #$hex/g; s/-st-accent-color/#$hex/g" "$css"
      done
      if [ -n "$bg" ]; then
          python3 - "$bg" <<'PYEOF'
import re, sys
bg = sys.argv[1]
for v in ('dark', 'light', 'high-contrast'):
    p = f'org/gnome/shell/theme/gnome-shell-{v}.css'
    t = open(p).read()
    t = re.sub(r'(#lockDialogGroup\s*\{[^}]*?background-color:\s*)#[0-9a-fA-F]{6}', r'\g<1>#' + bg, t)
    open(p, 'w').write(t)
PYEOF
      fi
      { echo '<?xml version="1.0"?><gresources><gresource prefix="/">'; sed 's|^/||;s|.*|<file>&</file>|' list.txt; echo '</gresource></gresources>'; } > t.xml
      glib-compile-resources --sourcedir=. --target=new.gresource t.xml ) || { rm -rf "$work"; return 1; }
    if [ -n "${GDM_DRYRUN:-}" ]; then echo "  GDM dry run: built $work/new.gresource"; return 0; fi
    pkexec bash -c 'set -e; G="$1"; [ -f "$G.orig" ] || cp -a "$G" "$G.orig"; install -o root -g root -m 644 "$2" "$G"; restorecon "$G" 2>/dev/null || true' _ "$GRES" "$work/new.gresource" \
        && echo "  GDM login screen accent -> #$hex (takes effect at next login screen)" \
        || { echo "  GDM: install cancelled or failed." >&2; rm -rf "$work"; return 1; }
    rm -rf "$work"
}

if [ "${1:-}" == "--gdm" ]; then
    gdm_apply "$CURRENT_HEX"
    exit $?
fi

if [ "${1:-}" == "--get" ]; then
    echo "$CURRENT_HEX"
    exit 0
fi

if [ $# -ne 1 ]; then
    echo "Usage: $0 <new-hex-color>   (e.g. $0 5a3e8b)"
    exit 1
fi

NEW_HEX="${1#\#}"
NEW_HEX="${NEW_HEX,,}"
if ! [[ "$NEW_HEX" =~ ^[0-9a-f]{6}$ ]]; then
    echo "Error: '$1' doesn't look like a valid 6-digit hex color." >&2
    exit 1
fi

OLD_HEX="${CURRENT_HEX,,}"
CSS="${SHELL_CSS:-$HOME/.themes/Adwaita-custom/gnome-shell/gnome-shell.css}"
HERE="$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")"

if [ ! -f "$CSS" ]; then
    echo "Error: $CSS not found - is this the right machine?" >&2
    exit 1
fi
if [ "$OLD_HEX" == "$NEW_HEX" ]; then
    echo "Current color is already #$NEW_HEX - shell theme nothing to do."
    if [ -z "${SHELL_CSS:-}" ] && [ "$(gdm_installed)" != "$NEW_HEX" ]; then
        echo "GDM is out of date ($(gdm_installed)) - re-applying."
        gdm_apply "$NEW_HEX" || true
    fi
    exit 0
fi

echo "Changing shell accent #$OLD_HEX -> #$NEW_HEX"

python3 - "$CSS" "$OLD_HEX" "$NEW_HEX" <<'PYEOF'
import re, sys
path, old, new = sys.argv[1:4]
text = open(path).read()

# 1+2: anchor-scoped (first hex within 300 chars after each anchor)
ANCHORS = [
    ".selection,\n.popup-menu-item:selected,\n.switcher-list .item-box:selected,\n.app-folder-popup:focus,\n.workspace-thumbnail:selected,\nStWidget:selected {",
    ".quick-toggle:checked {",
    ".quick-toggle-has-menu:checked .quick-toggle-menu-button {",
    ".calendar .calendar-day.calendar-today {",
]
for a in ANCHORS:
    i = text.find(a)
    if i == -1:
        print(f"  WARNING: anchor not found, skipped: {a.splitlines()[0]}...")
        continue
    win = text[i:i + 300]
    nwin, n = re.subn(r'#[0-9a-fA-F]{6}', '#' + new, win, count=1)
    text = text[:i] + nwin + text[i + 300:]
    print(f"  updated: {a.splitlines()[0]}...")

# 4: accent-mix fragments inside the qs-inactive-toggle block only
b = re.search(r'/\* BEGIN qs-inactive-toggle.*?/\* END qs-inactive-toggle \*/', text, re.S)
if b:
    blk, n = re.subn(r'st-mix\(#' + old + r', #ffffff, 60%\)', f'st-mix(#{new}, #ffffff, 60%)', b.group(0), flags=re.I)
    text = text[:b.start()] + blk + text[b.end():]
    print(f"  qs-inactive block: {n} accent-mix fragment(s)")
open(path, 'w').write(text)
PYEOF

# 3: regenerate the accent-unified block with the new literal
SHELL_CSS="$CSS" python3 "$HERE/gen-shell-accent-overrides.py" "$NEW_HEX"

SCRIPT_PATH="$(readlink -f "${BASH_SOURCE[0]}")"
sed -i "s/^CURRENT_HEX=\"${OLD_HEX}\"/CURRENT_HEX=\"${NEW_HEX}\"/" "$SCRIPT_PATH"
echo "  self-updated: CURRENT_HEX -> ${NEW_HEX}"

# GDM login screen (skipped for SHELL_CSS test runs); a failure here does not undo the shell change
if [ -z "${SHELL_CSS:-}" ]; then gdm_apply "$NEW_HEX" || echo "  (run $0 --gdm to retry the GDM part)"; fi

echo
echo "Done. Log out and back in to apply shell theme changes."
